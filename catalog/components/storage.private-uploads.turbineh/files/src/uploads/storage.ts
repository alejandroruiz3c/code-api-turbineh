import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { isAbsolute, relative, resolve, sep } from "node:path";
import { z } from "zod";
import { signRequest, type SigningKey } from "./sigv4";

/**
 * Private file storage (component storage.private-uploads.turbineh). Two drivers behind one interface:
 *  - "local": a directory outside public/ (UPLOADS_DIR, default .data/uploads) — development, unit tests, one server;
 *  - "s3": any S3-compatible bucket (S3_BASE_URL, S3_BUCKET, S3_REGION, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY),
 *    path-style requests signed with SigV4 — production and serverless hosts (their disk is not persistent).
 * Objects are never public: the only way to read one is the app's authorised download route.
 */
export interface StorageDriver {
  readonly kind: "local" | "s3";
  put(key: string, body: Uint8Array, contentType: string): Promise<void>;
  /** The bytes, or null when the object does not exist. */
  get(key: string): Promise<Uint8Array | null>;
  delete(key: string): Promise<void>;
}

/** Storage keys are generated by the app: "<org>/<uuid>" — never a user-supplied name. */
const KEY = /^[A-Za-z0-9_-]{1,64}\/[0-9a-f-]{36}$/;
export function assertKey(key: string): void {
  if (!KEY.test(key)) throw new Error("invalid storage key");
}

export function localDriver(dir: string): StorageDriver {
  const root = resolve(dir);
  const pathOf = (key: string) => {
    assertKey(key);
    const p = resolve(root, key);
    const rel = relative(root, p);
    if (rel.startsWith("..") || isAbsolute(rel)) throw new Error("invalid storage key");
    return p;
  };
  return {
    kind: "local",
    async put(key, body) {
      const p = pathOf(key);
      await mkdir(resolve(p, ".."), { recursive: true });
      await writeFile(p, body, { mode: 0o600 });
    },
    async get(key) {
      try {
        return new Uint8Array(await readFile(pathOf(key)));
      } catch (err) {
        if ((err as NodeJS.ErrnoException).code === "ENOENT") return null;
        throw err;
      }
    },
    async delete(key) {
      await rm(pathOf(key), { force: true });
    },
  };
}

export interface S3Settings extends SigningKey {
  baseUrl: string;
  bucket: string;
}

export function s3Driver(s: S3Settings): StorageDriver {
  const urlOf = (key: string) => {
    assertKey(key);
    return new URL(`${s.baseUrl.replace(/\/+$/, "")}/${s.bucket}/${key}`);
  };
  const call = async (method: string, key: string, body?: Uint8Array, type?: string) => {
    const url = urlOf(key);
    const headers = signRequest({
      method,
      url,
      body,
      headers: type ? { "content-type": type } : {},
      key: s,
    });
    // fetch sets Host itself (same value as the signed one).
    delete headers.host;
    return fetch(url, {
      method,
      headers,
      body: body ? Buffer.from(body) : undefined,
      cache: "no-store",
    });
  };
  return {
    kind: "s3",
    async put(key, body, contentType) {
      const res = await call("PUT", key, body, contentType);
      if (!res.ok) throw new Error(`storage PUT failed (${res.status})`);
    },
    async get(key) {
      const res = await call("GET", key);
      if (res.status === 404) return null;
      if (!res.ok) throw new Error(`storage GET failed (${res.status})`);
      return new Uint8Array(await res.arrayBuffer());
    },
    async delete(key) {
      const res = await call("DELETE", key);
      if (!res.ok && res.status !== 404) throw new Error(`storage DELETE failed (${res.status})`);
    },
  };
}

/** Whether `path` is `dir` or inside it. */
export function isInside(path: string, dir: string): boolean {
  return path === dir || path.startsWith(dir.endsWith(sep) ? dir : dir + sep);
}

const StorageEnv = z.object({
  STORAGE_DRIVER: z.enum(["local", "s3"]).optional(),
  UPLOADS_DIR: z.string().min(1).default(".data/uploads"),
  S3_BASE_URL: z.url().optional(),
  S3_BUCKET: z.string().min(3).max(63).optional(),
  S3_REGION: z.string().min(1).default("us-east-1"),
  S3_ACCESS_KEY_ID: z.string().min(1).optional(),
  S3_SECRET_ACCESS_KEY: z.string().min(1).optional(),
});

/** Driver from the environment: "s3" when STORAGE_DRIVER=s3 or S3_BUCKET is set, otherwise the local directory. */
export function driverFromEnv(
  source: Record<string, string | undefined> = process.env,
): StorageDriver {
  const env = StorageEnv.parse(
    Object.fromEntries(Object.entries(source).map(([k, v]) => [k, v === "" ? undefined : v])),
  );
  const s3 = env.STORAGE_DRIVER === "s3" || (!env.STORAGE_DRIVER && !!env.S3_BUCKET);
  if (!s3) {
    const dir = resolve(env.UPLOADS_DIR);
    // Never inside public/: files there would be served to anyone.
    if (isInside(dir, resolve("public"))) throw new Error("UPLOADS_DIR must be outside public/");
    return localDriver(dir);
  }
  if (!env.S3_BUCKET || !env.S3_ACCESS_KEY_ID || !env.S3_SECRET_ACCESS_KEY)
    throw new Error("S3 storage needs S3_BUCKET, S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY");
  return s3Driver({
    baseUrl: env.S3_BASE_URL ?? `https://s3.${env.S3_REGION}.amazonaws.com`,
    bucket: env.S3_BUCKET,
    region: env.S3_REGION,
    accessKeyId: env.S3_ACCESS_KEY_ID,
    secretAccessKey: env.S3_SECRET_ACCESS_KEY,
  });
}

let current: StorageDriver | null = null;
/** The app's storage (configured once per process). */
export function storage(): StorageDriver {
  current ??= driverFromEnv();
  return current;
}
