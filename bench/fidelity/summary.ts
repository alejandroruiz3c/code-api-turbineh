/**
 * Spec-fidelity summary of the 9 learning-round specs (ADR-0040), offline and deterministic (no models, no decider):
 * entity kinds, roles, constraints, domain patterns and the catalog component selected for each, and which criteria
 * each pattern touches. Usage: `pnpm exec tsx bench/fidelity/summary.ts > bench/frontiers/fidelity-<date>.md`.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  criterionTouches,
  selectPatternComponents,
  specFidelitySync,
  type PatternCatalogEntry,
} from "../../packages/compiler/src/fidelity/index.js";
import { LEARNING_SPECS } from "../../packages/compiler/src/fidelity/learning-specs.fixtures.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const componentsDir = join(root, "catalog/components");

/** Minimal manifest reading (status, provides, contract inputs) without a YAML dependency. */
function catalog(): PatternCatalogEntry[] {
  return readdirSync(componentsDir)
    .filter((id) => existsSync(join(componentsDir, id, "component.yaml")))
    .map((id) => {
      const y = readFileSync(join(componentsDir, id, "component.yaml"), "utf8");
      const provides =
        /provides:\s*\[([^\]]*)\]/
          .exec(y)?.[1]
          ?.split(",")
          .map((s) => s.trim())
          .filter(Boolean) ?? [];
      return {
        id,
        status: /^status:\s*(\S+)/m.exec(y)?.[1] ?? "",
        provides,
        inputs: [...y.matchAll(/(src\/[\w./-]+params\.json)/g)].map((m) => m[1] ?? ""),
      };
    });
}

const cat = catalog();
const out: string[] = [
  "# Spec fidelity — the 9 learning-round specs (offline, deterministic)",
  "",
  "Generated by `bench/fidelity/summary.ts` from `packages/compiler/src/fidelity/learning-specs.fixtures.ts` (BuildSpecs",
  "as the compiler model produced them in the 2026-10-13 learning round). No model and no decider were called. A",
  "pattern is *selected* only when an approved catalog component provides it; otherwise it is *missing* and the",
  "criteria it touches stay open. Criteria are not marked met here: that needs an assembled package and the gate.",
  "",
];
for (const s of LEARNING_SPECS) {
  const { fidelity } = specFidelitySync(s.prompt, s.spec, { knownEntities: s.recipeEntities });
  const sel = selectPatternComponents(fidelity.patterns, cat, s.spec.recipe);
  const p = fidelity.permissions;
  const c = fidelity.constraints;
  out.push(`## ${s.id} — ${s.spec.app_name}`, "");
  out.push("**Entity kinds**", "");
  out.push(
    ...(fidelity.entities.length
      ? fidelity.entities.map(
          (e) =>
            `- \`${e.name}\`: ${e.kind}${e.shape ? ` (${e.shape})` : ""}${e.parent ? `, parent ${e.parent}` : ""}, UI ${e.ui} — ${e.reason}`,
        )
      : ["- (none: the recipe provides the data model)"]),
    "",
  );
  out.push(
    "**Roles** (workspace role → spec role: actions, scope)",
    "",
    ...(["owner", "admin", "member"] as const).map((o) => {
      const r = p.byOrgRole[o];
      return `- ${o} → ${r.label}: ${r.actions.join(", ")}; scope ${r.scope.kind}${r.scope.of ? ` (${r.scope.of})` : ""}`;
    }),
    ...p.rules.map((r) => `- rule: ${r.text}`),
    ...(p.signUpEmailDomains.length
      ? [`- sign-up only: ${p.signUpEmailDomains.map((d) => `@${d}`).join(", ")}`]
      : []),
    "",
  );
  const facts = [
    `time zone ${c.timeZone.value} (${c.timeZone.source})`,
    c.currency ? `currency ${c.currency}` : null,
    c.uploads
      ? `uploads ≤ ${c.uploads.maxBytes ?? "n/s"} bytes, types ${c.uploads.types.join("/") || "n/s"}${c.uploads.private ? ", private" : ""}`
      : null,
    c.notice ? `notice ${c.notice.hours} h (${c.notice.about})` : null,
    c.openingHours.length
      ? `opening hours ${c.openingHours.map((h) => `${h.weekday} ${h.open}–${h.close}`).join(", ")}`
      : null,
    c.prices.length
      ? `prices ${c.prices.map((x) => `${x.name} ${x.minutes} min ${x.price} ${x.currency}`).join("; ")}`
      : null,
    c.statusLists.length
      ? `statuses ${c.statusLists.map((l) => `${l.field}: ${l.values.join(" → ")}`).join("; ")}`
      : null,
    c.sort.length ? `sort ${c.sort.map((x) => `${x.field} ${x.direction}`).join(", ")}` : null,
    c.schedules.length
      ? `schedules ${c.schedules.map((x) => `\`${x.cron}\` ${x.timeZone}`).join(", ")}`
      : null,
    c.emailDomains.length ? `email domains ${c.emailDomains.join(", ")}` : null,
    c.numbers.length ? `numbers ${c.numbers.map((n) => `${n.what}=${n.value}`).join(", ")}` : null,
  ].filter(Boolean);
  out.push(
    "**Constraints**",
    "",
    ...facts.map((f) => `- ${f}`),
    ...c.assumptions.map((a) => `- default: ${a}`),
    "",
  );
  out.push("**Domain patterns**", "");
  for (const m of fidelity.patterns) {
    const chosen = sel.selected.find((x) => x.id === m.id);
    out.push(
      `- \`${m.id}\`: ${chosen ? `selected \`${chosen.component}\` (params → \`${chosen.paramsFile}\`)` : "missing in catalog"} — params \`${JSON.stringify(m.params).slice(0, 220)}${JSON.stringify(m.params).length > 220 ? "…" : ""}\``,
    );
  }
  if (fidelity.patterns.length === 0) out.push("- (none)");
  out.push("", "**Criteria**", "");
  let touched = 0;
  for (const crit of s.spec.acceptance_criteria) {
    const by = fidelity.patterns.filter((m) => criterionTouches(crit, m)).map((m) => m.id);
    if (by.length) touched++;
    const selectedBy = by.filter((id) => sel.selected.some((x) => x.id === id));
    out.push(
      `- ${crit} — ${by.length ? `pattern ${by.join(", ")}${selectedBy.length ? " (component selected: proof comes from its acceptance.yaml once assembled)" : " (component missing: open)"}` : "open (no pattern)"}`,
    );
  }
  out.push(
    "",
    `Met: 0 (not assembled here) · touched by a pattern: ${touched}/${s.spec.acceptance_criteria.length} · selected patterns: ${sel.selected.length}/${fidelity.patterns.length}`,
    "",
  );
}
process.stdout.write(`${out.join("\n")}\n`);
