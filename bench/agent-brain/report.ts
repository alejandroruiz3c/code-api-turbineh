/**
 * Markdown table of agent-brain runs: pnpm --filter @turbineh/bench exec tsx agent-brain/report.ts label1 label2 …
 * Writes bench/agent-brain/RESULTS.md and prints it; with --print it only prints the tables (to paste into a section).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface Summary {
  label: string;
  brain: string;
  success: string;
  successByKind: Record<string, string>;
  turnsPerConversation: number;
  latencyPerTurnMs: { p50: number; p90: number; p95: number; max: number };
  timePerConversationMs: { p50: number; p95: number };
  tokens: Record<string, { input: number; output: number; cacheRead: number; cacheWrite: number }>;
  costPer1000ConversationsUsd: number;
  costPer1000ConversationsInclHedgesUsd?: number;
  hedgedCalls?: number;
  chatCalls?: number;
  conversations: number;
}

const dir = join(import.meta.dirname, "runs");
const printOnly = process.argv.includes("--print");
const labels = process.argv.slice(2).filter((a) => a !== "--print");
const runs = labels.map(
  (l) => (JSON.parse(readFileSync(join(dir, `${l}.json`), "utf8")) as { summary: Summary }).summary,
);
const s = (ms: number) => (ms / 1000).toFixed(2);
const kinds = [...new Set(runs.flatMap((r) => Object.keys(r.successByKind)))];
const tokens = (r: Summary) =>
  Math.round(
    Object.values(r.tokens).reduce(
      (n, t) => n + t.input + t.output + t.cacheRead + t.cacheWrite,
      0,
    ) / r.conversations,
  );
const lines = [
  "| Run | Brain | Success | Turns/conv | Turn p50 s | p90 | p95 | max | Conv p50 s | Conv p95 s | Tokens/conv | USD / 1,000 conv | Hedged chat calls | USD / 1,000 incl. hedges ¹ |",
  "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
  ...runs.map(
    (r) =>
      `| ${r.label} | ${r.brain} | ${r.success} | ${r.turnsPerConversation} | ${s(r.latencyPerTurnMs.p50)} | ${s(r.latencyPerTurnMs.p90)} | ${s(r.latencyPerTurnMs.p95)} | ${s(r.latencyPerTurnMs.max)} | ${s(r.timePerConversationMs.p50)} | ${s(r.timePerConversationMs.p95)} | ${tokens(r)} | ${r.costPer1000ConversationsUsd.toFixed(2)} | ${r.brain === "turbineh" && r.chatCalls !== undefined ? `${r.hedgedCalls ?? 0}/${r.chatCalls}` : "-"} | ${(r.costPer1000ConversationsInclHedgesUsd ?? r.costPer1000ConversationsUsd).toFixed(2)} |`,
  ),
  "",
  "¹ Cancelled hedge requests counted at the answer's own tokens: an upper bound [est.]; the app is billed only the answer.",
  "",
  `| Run | ${kinds.join(" | ")} |`,
  `|---|${kinds.map(() => "---").join("|")}|`,
  ...runs.map((r) => `| ${r.label} | ${kinds.map((k) => r.successByKind[k] ?? "-").join(" | ")} |`),
];
const md = `# Agent brain comparison — results\n\nGenerated by \`agent-brain/report.ts\` from \`runs/*.json\`. Prices and labels: \`prices.ts\`.\n\n${lines.join("\n")}\n`;
if (!printOnly) writeFileSync(join(import.meta.dirname, "RESULTS.md"), md);
console.log(printOnly ? lines.join("\n") : md);
