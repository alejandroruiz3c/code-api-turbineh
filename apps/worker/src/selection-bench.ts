const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const label = process.argv[2] ?? "run";
const cardsAt = process.argv.indexOf("--cards");
const cards = (cardsAt > 0 ? process.argv[cardsAt + 1] : "compact") as CardMode;
loadLocalEnv(repoRoot);
const decider = deciderFromEnv(readEnv());
const catalog = loadCatalog(join(repoRoot, "catalog/components"), { cards });
const rows = [];
for (const c of CASES) {
  const candidates = candidatesFor([c.capability], catalog);
  const t0 = performance.now();
  const r = await selectComponents(
    {
      app: { recipe: "saas-crud", summary: c.summary, acceptance_criteria: [c.summary] },
      candidates,
    },
    decider,
  );
  const ms = Math.round(performance.now() - t0);
  const d = r.decisions[0];
  rows.push({
    capability: c.capability,
    expected: c.expected,
    chosen: d?.best?.id ?? null,
    correct: d?.best?.id === c.expected,
    pChosen: d?.best?.p ?? 0,
    coversExpected: d?.covers[c.expected] ?? 0,
    candidates: candidates[c.capability]?.length ?? 0,
    ms,
  });
  console.log(
    `${d?.best?.id === c.expected ? "✓" : "✗"} ${c.capability} → ${d?.best?.id} (${ms} ms)`,
  );
}
const n = rows.length;
const summary = {
  label,
  cards,
  cases: n,
  accuracy: rows.filter((r) => r.correct).length / n,
  meanPChosenWhenCorrect:
    rows.filter((r) => r.correct).reduce((a, r) => a + r.pChosen, 0) /
    Math.max(1, rows.filter((r) => r.correct).length),
  meanCoversExpected: rows.reduce((a, r) => a + r.coversExpected, 0) / n,
  latencyMs: {
    mean: Math.round(rows.reduce((a, r) => a + r.ms, 0) / n),
    p50: [...rows].sort((a, b) => a.ms - b.ms)[Math.floor(n / 2)]?.ms ?? 0,
  },
  decider: decider.id,
  at: new Date().toISOString(),
};
const out = join(repoRoot, "bench/results", `${summary.at.slice(0, 10)}-selection-${label}.json`);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${JSON.stringify({ summary, rows }, null, 2)}\n`);
console.log(JSON.stringify(summary));
