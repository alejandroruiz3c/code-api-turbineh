/**
 * `pnpm --filter @turbineh/worker run verify:spec <fixture> [--quick | --assemble-only] [--local-db]
 * [--without <component,…>] [--json]`
 *
 * Compiles a learning-round spec offline (ADR-0043): no model and no decider — the BuildSpec comes from the fidelity
 * fixtures (`@turbineh/compiler/learning-specs`), everything else is the pipeline's deterministic path (spec
 * fidelity, pattern components selected by code with params validated against their schemas, native components for
 * the spec's capabilities). It assembles the package twice — before (generic CRUD, as before ADR-0043) and after
 * (generated by kind with roles, constraints and domain components) — runs the gate on the "after" package (full by
 * default, `--quick` = lint + typecheck + unit) and prints the summary: entities and pages generated before vs after,
 * roles, patterns, criteria met / open.
 *  - `<fixture>`: a fixture id (saas-crud, tracker, internal-tool…) or the app name (Fieldnote, Kilnwise, Pixelyard…).
 *  - `--without`: components treated as absent (exercises the generic fallbacks, e.g. timeline and settings pages).
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  assemble,
  finalizeAcceptance,
  hasRecipe,
  mergedRecipe,
  readOwners,
  recipeChain,
  type SelectedComponent,
} from "@turbineh/assembler";
import { detectDomains, type BuildSpec } from "@turbineh/compiler";
import { LEARNING_SPECS, type LearningSpec } from "@turbineh/compiler/learning-specs";
import { gateFailures, quickCheck, verify, type VerifyResult } from "@turbineh/verifier";
import { loadCatalog } from "./catalog-source.js";
import { nativeSelection } from "./combinations.js";
import { mergeDomains, wireFidelitySync, type WiredFidelity } from "./fidelity-wiring.js";

const argv = process.argv.slice(2);
const flag = (name: string) => {
  const at = argv.indexOf(name);
  if (at >= 0) argv.splice(at, 1);
  return at >= 0;
};
const quick = flag("--quick");
const assembleOnly = flag("--assemble-only");
const localDb = flag("--local-db");
const asJson = flag("--json");
const withoutAt = argv.indexOf("--without");
const without =
  withoutAt >= 0 ? (argv.splice(withoutAt, 2)[1] ?? "").split(",").filter(Boolean) : [];
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const recipesDir = join(repoRoot, "catalog/recipes");
const componentsDir = join(repoRoot, "catalog/components");

export function findFixture(name: string): LearningSpec | null {
  const n = name.toLowerCase();
  return (
    LEARNING_SPECS.find((s) => s.id === n || s.spec.app_name.toLowerCase() === n) ??
    LEARNING_SPECS.find((s) => s.spec.app_name.toLowerCase().startsWith(n)) ??
    null
  );
}

/** Native components for the spec's capabilities (the decider's choice among natives, made by code here). */
function capabilityNatives(spec: BuildSpec, recipeId: string): string[] {
  const merged = mergedRecipe(recipeChain(recipesDir, recipeId));
  const provided = new Set(merged.providedCapabilities ?? []);
  const catalog = loadCatalog(componentsDir, { cards: "oneliner" });
  return spec.capabilities.flatMap((cap) => {
    if (provided.has(cap)) return [];
    const c = catalog.find(
      (x) => x.status === "approved" && x.pkg.name.startsWith("turbineh/") && x.provides.includes(cap),
    );
    return c && !without.includes(c.id) ? [c.id] : [];
  });
}

interface Snapshot {
  dir: string;
  entities: { entity: string; owner: string; files: number }[];
  pages: string[];
  components: string[];
  criteria: { criterion: string; status: string; tests: string[] }[];
}

function snapshot(dir: string, components: string[]): Snapshot {
  const owners = readOwners(dir);
  const byEntity = new Map<string, number>();
  for (const [file, owner] of Object.entries(owners))
    if (owner.startsWith("entity:")) byEntity.set(owner, (byEntity.get(owner) ?? 0) + 1);
  const pages = Object.entries(owners)
    .filter(([f, o]) => o.startsWith("entity:") && /^src\/app\/.*page\.tsx$/.test(f) && !f.includes("[id]"))
    .map(([f]) => `/${f.replace(/^src\/app\//, "").replace(/\/?page\.tsx$/, "")}`)
    .sort();
  const acc = join(dir, ".turbineh/acceptance.json");
  return {
    dir,
    entities: [...byEntity].map(([owner, files]) => ({
      entity: owner.slice("entity:".length),
      owner,
      files,
    })),
    pages,
    components,
    criteria: existsSync(acc) ? (JSON.parse(readFileSync(acc, "utf8")) as Snapshot["criteria"]) : [],
  };
}

function build(
  s: LearningSpec,
  mode: "before" | "after",
): { snap: Snapshot; wired: WiredFidelity | null } {
  const recipeId = hasRecipe(recipesDir, s.spec.recipe) ? s.spec.recipe : "saas-crud";
  const chain = recipeChain(recipesDir, recipeId).map((m) => m.id);
  const merged = mergedRecipe(recipeChain(recipesDir, recipeId));
  const base = structuredClone(s.spec);
  base.capabilities = [
    ...new Set([...base.capabilities, ...merged.defaultCapabilities]),
  ] as BuildSpec["capabilities"];
  const wired =
    mode === "after"
      ? wireFidelitySync(s.prompt, base, {
          recipeId,
          recipeChain: chain,
          componentsDir,
          knownEntities: merged.providedEntities,
          exclude: without,
        })
      : null;
  const spec = wired?.spec ?? base;
  const domains = mergeDomains(wired?.wired.selected ?? [], detectDomains(s.prompt, recipeId, spec.app_name));
  const extra = [
    ...domains.map((d) => d.component),
    ...capabilityNatives(spec, recipeId),
  ].filter((id) => !without.includes(id));
  const { selected } = nativeSelection(repoRoot, recipeId, s.prompt, extra);
  const outDir = join(mkdtempSync(join(tmpdir(), `spec-${s.id}-${mode}-`)), "app");
  assemble({
    buildId: `verify-spec-${mode}`,
    recipesDir,
    recipe: recipeId,
    outDir,
    spec,
    selected: selected.filter((x: SelectedComponent) => !without.includes(x.component.id)),
    gaps: [],
    domains: domains.filter((d) => selected.some((x) => x.component.id === d.component)),
    ...(wired ? { fidelity: wired.assembly } : {}),
  });
  return { snap: snapshot(outDir, selected.map((x) => x.component.id)), wired };
}

async function gate(dir: string): Promise<VerifyResult> {
  const git = (...args: string[]) =>
    execFileSync("git", ["-c", "user.name=check", "-c", "user.email=check@example.com", ...args], {
      cwd: dir,
      stdio: "pipe",
    });
  git("init", "-q", "-b", "main");
  git("add", "-A");
  git("commit", "-q", "-m", "verify spec");
  return quick ? quickCheck(dir) : verify(dir, { localDb });
}

const count = (c: Snapshot["criteria"], st: string) => c.filter((x) => x.status === st).length;

async function main() {
  const name = argv[0] ?? "";
  const s = findFixture(name);
  if (!s) {
    console.error(
      `unknown fixture "${name}"; one of: ${LEARNING_SPECS.map((x) => `${x.id} (${x.spec.app_name})`).join(", ")}`,
    );
    process.exit(2);
  }
  const before = build(s, "before").snap;
  const { snap: after, wired } = build(s, "after");
  let result: VerifyResult | null = null;
  let criteria = after.criteria;
  if (!assembleOnly) {
    result = await gate(after.dir);
    if (!quick) criteria = finalizeAcceptance(after.dir, result.ok);
  }
  const summary = {
    fixture: s.id,
    app: s.spec.app_name,
    without,
    before: {
      dir: before.dir,
      entities: before.entities.map((e) => e.entity),
      pages: before.pages,
      criteria: { covered: count(before.criteria, "covered"), open: count(before.criteria, "open") },
    },
    after: {
      dir: after.dir,
      entities: wired?.assembly
        ? JSON.parse(readFileSync(join(after.dir, ".turbineh/fidelity.json"), "utf8")).entities
        : [],
      pages: after.pages,
      roles: wired
        ? JSON.parse(readFileSync(join(after.dir, ".turbineh/fidelity.json"), "utf8")).roles.map(
            (r: { key: string; label: string; can: string[]; scope: { kind: string } }) =>
              `${r.key} (${r.label}): ${r.can.join(", ")}${r.scope.kind !== "all" ? ` · scope ${r.scope.kind}` : ""}`,
          )
        : [],
      patterns: wired?.wired.patterns.map((p) => ({
        id: p.id,
        status: p.status,
        component: p.component,
        ...(p.reason ? { reason: p.reason } : {}),
      })),
      components: after.components,
      gate: result
        ? {
            mode: quick ? "quick" : "full",
            ok: result.ok,
            steps: result.steps.map((x) => `${x.name}:${x.ok ? "ok" : "FAIL"}`),
            failures: gateFailures(result).slice(0, 10),
          }
        : null,
      criteria: {
        met: count(criteria, "met"),
        covered: count(criteria, "covered"),
        open: count(criteria, "open"),
        list: criteria.map((c) => ({ status: c.status, criterion: c.criterion, tests: c.tests })),
      },
    },
  };
  writeFileSync(join(after.dir, ".turbineh/verify-spec.json"), `${JSON.stringify(summary, null, 2)}\n`);
  if (asJson) console.log(JSON.stringify(summary, null, 2));
  else {
    const a = summary.after;
    console.log(
      [
        `# ${s.spec.app_name} (${s.id})${without.length ? ` without ${without.join(", ")}` : ""}`,
        `before: ${before.entities.length} generated entities, pages ${before.pages.join(" ") || "—"}; criteria covered ${summary.before.criteria.covered}, open ${summary.before.criteria.open}`,
        `after:  ${a.entities.length} entities, pages ${a.pages.join(" ") || "—"}`,
        ...a.entities.map(
          (e: { entity: string; kind: string; ui: string }) => `  - ${e.entity}: ${e.kind} → ${e.ui}`,
        ),
        `roles:  ${a.roles.join(" | ")}`,
        `patterns: ${(a.patterns ?? []).map((p) => `${p.id}=${p.status}${p.component ? `(${p.component})` : ""}`).join(", ") || "—"}`,
        a.gate ? `gate (${a.gate.mode}): ${a.gate.ok ? "PASS" : "FAIL"} ${a.gate.steps.join(" ")}` : "gate: not run",
        `criteria: met ${a.criteria.met}, covered ${a.criteria.covered}, open ${a.criteria.open} of ${criteria.length}`,
        `package: ${after.dir}`,
      ].join("\n"),
    );
  }
  process.exitCode = result && !result.ok ? 1 : 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) await main();
